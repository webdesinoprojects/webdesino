function normalizeName(raw) {
  let s = raw.trim();
  // Fix known OCR / encoding typo in Gujarat list
  if (s.includes("Mendar") && /да/.test(s)) {
    s = s.replace(/Mendarда/g, "Mendarada");
  }
  return s;
}

function parse(text) {
  const lines = text.split(/\r?\n/);
  /** @type {Record<string, string[]>} */
  const out = {};
  /** @type {Map<string, Set<string>>} */
  const seenByState = new Map();

  let currentKey = null;

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) continue;
    if (/^={3,}$/.test(line)) continue;
    if (/^GRAND TOTAL/i.test(line)) break;

    const hm = line.match(/^(.+?)\s*[—–-]\s*\d+\s+Locations?/i);
    if (hm) {
      const headerNorm = hm[1].trim().replace(/\s+/g, " ");
      const upperKey = headerNorm.toUpperCase();
      currentKey = HEADER_TO_KEY[upperKey];
      if (!currentKey) {
        console.warn("Unknown section header:", line);
        currentKey = null;
        continue;
      }
      if (!out[currentKey]) {
        out[currentKey] = [];
        seenByState.set(currentKey, new Set());
      }
      continue;
    }

    const nm = line.match(/^\d+\.\s*(.+)$/);
    if (nm && currentKey) {
      const name = normalizeName(nm[1]);
      if (!name) continue;
      const seen = seenByState.get(currentKey);
      if (seen.has(name)) continue;
      seen.add(name);
      out[currentKey].push(name);
    }
  }

  return out;
}

function emitTs(data) {
  const keys = Object.keys(data).sort((a, b) => a.localeCompare(b, "en"));
  const lines = [
    "/**",
    " * Auto-generated by scripts/parse-locations-paste.mjs — do not edit by hand.",
    " * Keys match lib/location-states.ts values.",
    " */",
    "export const ADDITIONAL_LOCATIONS_BY_STATE: Record<string, string[]> = {",
  ];

  for (const k of keys) {
    const arr = data[k];
    lines.push(`  ${JSON.stringify(k)}: [`);
    for (const name of arr) {
      lines.push(`    ${JSON.stringify(name)},`);
    }
    lines.push(`  ],`);
  }
  lines.push("};");
  lines.push("");
  return lines.join("\n");
}

function readInputText() {
  const arg = process.argv[2];
  const chunksDir = path.join(root, "scripts", "locations-paste-chunks");
  if (arg && arg !== "--chunks" && fs.existsSync(arg)) {
    return fs.readFileSync(arg, "utf8");
  }
  const single = path.join(root, "scripts", "locations-paste.txt");
  if (fs.existsSync(single)) {
    return fs.readFileSync(single, "utf8");
  }
  if (fs.existsSync(chunksDir)) {
    const files = fs
      .readdirSync(chunksDir)
      .filter((f) => f.endsWith(".txt"))
      .sort();
    if (files.length > 0) {
      return files
        .map((f) => fs.readFileSync(path.join(chunksDir, f), "utf8"))
        .join("\n");
    }
  }
  return null;
}

function main() {
  const outPath = path.join(root, "lib", "location-seeds", "additional-locations.ts");

  const text = readInputText();
  if (text == null) {
    console.error(
      "Missing input: add scripts/locations-paste.txt or scripts/locations-paste-chunks/*.txt"
    );
    process.exit(1);
  }
  const data = parse(text);

  const keys = Object.keys(data);
  console.log("States parsed:", keys.length, keys.join(", "));

  let total = 0;
  for (const k of keys) {
    const n = data[k].length;
    total += n;
    console.log(`  ${k}: ${n}`);
  }
  console.log("Total locations:", total);

  fs.writeFileSync(outPath, emitTs(data), "utf8");
  console.log("Wrote", outPath);
}

main();
